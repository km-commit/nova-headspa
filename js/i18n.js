const NovaI18N = (function () {
  const STORE = 'nova_lang';
  const SUPPORTED = ['fr', 'en'];
  let lang = 'fr';

  function dict() { return I18N[lang]; }
  function t(key) { return (dict() && dict()[key] != null) ? dict()[key] : key; }

  function apply(next) {
    lang = SUPPORTED.includes(next) ? next : 'fr';
    const d = I18N[lang];
    document.documentElement.lang = lang;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const v = d[el.dataset.i18n];
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const v = d[el.dataset.i18nPlaceholder];
      if (v != null) el.setAttribute('placeholder', v);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
      const v = d[el.dataset.i18nAriaLabel];
      if (v != null) el.setAttribute('aria-label', v);
    });
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
      const v = d[el.dataset.i18nAlt];
      if (v != null) el.setAttribute('alt', v);
    });
    document.querySelectorAll('[data-i18n-content]').forEach(el => {
      const v = d[el.dataset.i18nContent];
      if (v != null) el.setAttribute('content', v);
    });

    const sw = document.getElementById('lang-switch');
    if (sw) sw.textContent = lang === 'fr' ? 'EN' : 'FR';

    try { localStorage.setItem(STORE, lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('nova:langchange', { detail: { lang } }));
  }

  function init() {
    let saved = null;
    try { saved = localStorage.getItem(STORE); } catch (e) {}
    apply(saved || 'fr');

    const sw = document.getElementById('lang-switch');
    if (sw) sw.addEventListener('click', () => apply(lang === 'fr' ? 'en' : 'fr'));
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  return { t, apply, get lang() { return lang; } };
})();

window.NovaI18N = NovaI18N;
